import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import * as THREE from 'three';
import {GLTFLoader} from 'three/addons/loaders/GLTFLoader.js';
import {createCorvetteModel} from '../src/corvette-model.js';
const bytes=await fs.readFile(new URL('../public/models/corvette-c7/corvette-c7.glb',import.meta.url));
const buffer=bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength);
const gltf=await new GLTFLoader().parseAsync(buffer,'');
const m=createCorvetteModel(gltf.scene);
assert.equal(m.wheels.length,4);assert.equal(m.frontWheels.length,2);
assert.equal(m.suspensionPivots.length,4);
const oldMatrices=m.wheels.map(w=>w.getWorldPosition(new THREE.Vector3()).clone());
const restBody=m.bodyRig.position.y;
m.setPose({steering:.4,spin:7.3,suspension:.02});
m.setCustomization({paint:'#ff1122',finish:'matte',tire:'slick',rideHeight:.03});
assert.equal(m.materials.paint.color.getHexString(),'ff1122');
assert.equal(m.materials.paint.roughness,.72);
assert.ok(Math.abs(m.bodyRig.position.y-restBody-.05)<1e-9);
m.wheels.forEach((w,i)=>{
 assert.ok(w.getWorldPosition(new THREE.Vector3()).distanceTo(oldMatrices[i])<1e-8,'wheel centers must stay grounded during body suspension');
 assert.equal(w.rotation.x,7.3);
 assert.ok(w.getWorldScale(new THREE.Vector3()).distanceTo(new THREE.Vector3(1,1,1))<1e-7,'pivot rig scale must remain unit');
});
m.frontWheels.forEach(w=>assert.equal(w.rotation.y,.4));
assert.ok(m.wheelSlots.every(w=>w.treads.every(t=>!t.visible)));
m.setCustomization({tire:'sport'});assert.ok(m.wheelSlots.every(w=>w.sport.visible));
m.setCustomization({tire:'street'});assert.ok(m.wheelSlots.every(w=>w.treads.every(t=>t.visible)));
m.setPose({steering:99,suspension:99});assert.equal(m.frontWheels[0].rotation.y,.45);
const independently=createCorvetteModel(gltf.scene);assert.notEqual(independently.materials.paint,m.materials.paint);
assert.notEqual(independently.materials.paint.color.getHex(),m.materials.paint.color.getHex());
const result={pass:true,...m.stats,fileBytes:bytes.byteLength,checks:['GLB load','rig bindings','steering and spin','body suspension preserves wheel centers','unit pivot scale','tire slots','material isolation','travel clamps']};
await fs.writeFile(new URL('../art/corvette-c7/runtime-check.json',import.meta.url),JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result,null,2));m.dispose();independently.dispose();
